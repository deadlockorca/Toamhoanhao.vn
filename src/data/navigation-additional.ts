const translations = Object.fromEntries(
  rows.map(([source, ...values]) => [source, values]),
) as Record<string, string[]>;

function translateLabel(locale: AdditionalLocale, label: string) {
  const translated = translations[label]?.[index[locale]];
  if (translated) return translated;
  if (/^Apartment \d/.test(label)) {
    const area = label.replace(/^Apartment /, "").replaceAll("m2", "m²");
    const prefix: Record<AdditionalLocale, string> = {
      ko: "아파트",
      sv: "Lägenhet",
      fr: "Appartement",
      ru: "Квартира",
      es: "Apartamento",
      zh: "公寓",
    };
    return `${prefix[locale]} ${area}`;
  }
  return label;
}

export function translateAdditionalNavigation(
  locale: AdditionalLocale,
  item: NavigationItem,
): NavigationItem {
  return {
    ...item,
    label: translateLabel(locale, item.label),
    children: item.children?.map((child) => ({
      ...child,
      label: translateLabel(locale, child.label),
      children: child.children?.map((grandchild) => ({
        ...grandchild,
        label: translateLabel(locale, grandchild.label),
      })),
    })),
  };
}
